    public static string Get(string key, DockLanguage language)
    {
        var pair = Values[key];
        var russian = language == DockLanguage.Russian ||
            (language == DockLanguage.System && CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "ru");
        return russian ? pair.Russian : pair.English;
    }
